const {assert, path, base, output, assertResponsive, assertAccessible} = require('./helpers.cjs');

module.exports = async function research(page) {
  await page.goto(`${base}/evaluation`);
  await page.locator('#compare:not([disabled])').waitFor();
  await page.locator('#comparison-sample').focus();
  await page.keyboard.press('Tab');
  assert.equal(await page.evaluate(() => document.activeElement.id), 'comparison-file');
  const picker = page.locator('label[for="comparison-file"]');
  assert.equal(await picker.evaluate(label => getComputedStyle(label).outlineStyle), 'solid');
  const response = page.waitForResponse(response => response.url().endsWith('/api/comparisons') && response.status() === 200);
  await page.getByRole('button', {name: 'Compare pipelines', exact: true}).click();
  const data = await (await response).json();
  assert.deepEqual(data.comparisons.map(item => item.backend), ['easyocr', 'paddleocr', 'trocr']);
  assert.equal(data.comparisons.filter(item => item.status === 'success').length, 3);
  await page.locator('#comparison-results .field-card').first().waitFor();
  const text = await page.locator('#comparison-results').innerText();
  for (const name of ['EasyOCR', 'PaddleOCR', 'TrOCR']) assert.match(text, new RegExp(name));
  assert.equal(await page.locator('#evaluation').count(), 0);
  await assertResponsive(page, '/evaluation');
  await assertAccessible(page);
  await page.screenshot({path: path.join(output, 'evaluation-desktop.png'), fullPage: true});
  const ids = await page.locator('[id]').evaluateAll(nodes => nodes.map(node => node.id));
  assert.equal(new Set(ids).size, ids.length, 'Comparison columns must not duplicate DOM IDs.');
  let analysisRequests = 0;
  const countAnalysis = request => {
    if (request.url().endsWith('/api/analysis')) analysisRequests += 1;
  };
  page.on('request', countAnalysis);
  await page.goto(`${base}/models`);
  await page.getByRole('link', {name: 'How it works', exact: true}).waitFor();
  await page.locator('#walkthrough-viewer img').waitFor();
  assert.equal(analysisRequests, 0, 'Opening the page should only load the sample photo.');
  const find = page.getByRole('button', {name: '2. Find the sign'});
  await find.focus();
  await page.keyboard.press('Enter');
  await page.locator('#walkthrough-viewer .box').first().waitFor();
  assert.equal(await page.locator('#walkthrough-viewer a.box').count(), 0);
  await page.getByRole('button', {name: 'Hide detection boxes'}).click();
  assert.equal(await page.locator('#walkthrough-viewer .box').first().isVisible(), false);
  await page.getByRole('button', {name: 'Show detection boxes'}).click();
  await page.getByRole('button', {name: '3. Read the text'}).click();
  await page.locator('#walkthrough-result .crop').first().waitFor();
  assert.match(await page.locator('#walkthrough-result').innerText(), /124/);
  await page.getByRole('button', {name: '4. Match the route'}).click();
  assert.match(await page.locator('#walkthrough-result').innerText(), /Saint Michael's Bus Terminal/);
  assert.match(await page.locator('#walkthrough-timings').innerText(), /Total\s+\d+ ms/);
  await page.getByRole('button', {name: '5. Say it'}).click();
  const transcript = page.locator('.walkthrough-transcript');
  assert.match(await transcript.innerText(), /Bus 1 2 4 to Saint Michael's Bus Terminal/);
  assert.equal(await page.getByRole('button', {name: 'Stop speech', exact: true}).isDisabled(), true);
  await page.getByRole('radio', {name: '中文'}).check();
  assert.match(await transcript.innerText(), /124号巴士，开往/);
  await page.getByRole('radio', {name: 'English'}).check();
  assert.equal(analysisRequests, 1, 'All steps should share the same analysis.');
  page.off('request', countAnalysis);
  const details = page.locator('.models-details');
  assert.equal(await details.getAttribute('open'), null);
  await details.locator('summary').click();
  await details.getByText(/yolo11s-best\.pt/).waitFor();
  await details.getByRole('heading', {name: 'Runtime', exact: true}).waitFor();
  await assertResponsive(page, '/models');
  await assertAccessible(page);
  await details.locator('summary').click();
  await page.getByRole('button', {name: '1. Photo'}).click();
  await page.screenshot({path: path.join(output, 'models-desktop.png'), fullPage: true});
  await page.setViewportSize({width: 320, height: 1000});
  await assertAccessible(page);
  console.log('Evaluation/Models: real comparison, five-step walkthrough, language selection, technical details, responsive and accessibility passed.');
};
